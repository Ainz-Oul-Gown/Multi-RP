// 3. Выполнение тестирования
let totalTurns = 0;
let passedTurns = 0;
const reportRows = [];

for (const ds of datasets) {
  console.log(`\n───────────────────────────────────────────────────────────────────────`);
  console.log(`📂 [${ds.id}] ${ds.theme}`);
  console.log(`   Биом: ${ds.biome}`);
  console.log(`   Герои: ${ds.playerA.name} (${ds.playerA.race} ${ds.playerA.class}) & ${ds.playerB.name} (${ds.playerB.race} ${ds.playerB.class})`);
  console.log(`   NPC: ${ds.npc.name} (${ds.npc.role})`);
  console.log(`───────────────────────────────────────────────────────────────────────`);

  for (const turn of ds.turns) {
    totalTurns++;
    console.log(`\n  ▶ ХОД ${turn.turnNum} [${turn.actor} → ${turn.targetName}]`);
    console.log(`    Действие: "${turn.action}"`);

    // Анализ качества ответа
    const otherPlayer = turn.actor.includes(ds.playerA.name.split(' ')[0]) ? ds.playerB.name : ds.playerA.name;
    const q = evaluateQuality(turn.dmResponse, otherPlayer);

    // Анализ памяти
    let memoryOk = true;
    const memoryDetails = [];
    if (turn.checksMemoryOfTurns) {
      for (const pattern of turn.checksMemoryOfTurns) {
        const found = pattern.test(turn.dmResponse);
        if (found) {
          memoryDetails.push(`✅ ${pattern}`);
        } else {
          memoryDetails.push(`❌ ${pattern}`);
          memoryOk = false;
        }
      }
    }

    const allOk = q.isSufficientLength && q.noTechTags && q.hasSensory && q.noPuppeteering && memoryOk;
    if (allOk) {
      passedTurns++;
      console.log(`    ✅ ОЦЕНКА: ОТЛИЧНО`);
    } else {
      console.log(`    ⚠️ ОЦЕНКА: ЗАМЕЧАНИЯ`);
    }

    console.log(`       • Слов в ответе: ${q.wordCount} ${q.isSufficientLength ? '✅' : '❌'}`);
    console.log(`       • Без тех. тегов: ${q.noTechTags ? '✅' : '❌'}`);
    console.log(`       • Чувственные детали: ${q.hasSensory ? '✅' : '❌'}`);
    console.log(`       • Защита от кукловодства (No Godmoding): ${q.noPuppeteering ? '✅ (Свобода выбора соблюдена)' : `❌ (${q.violations.join(', ')})`}`);
    if (turn.checksMemoryOfTurns) {
      console.log(`       • Память ДМ о предыдущих ходах: ${memoryOk ? '✅' : '❌'} [${memoryDetails.join(', ')}]`);
    }

    reportRows.push({
      dataset: ds.id,
      turn: turn.turnNum,
      actor: turn.actor,
      target: turn.targetName,
      wordCount: q.wordCount,
      noTechTags: q.noTechTags,
      sensory: q.hasSensory,
      noGodmoding: q.noPuppeteering,
      memoryRecall: turn.checksMemoryOfTurns ? (memoryOk ? '100%' : '50%') : 'N/A',
      verdict: allOk ? 'PASS' : 'WARN',
    });
  }
}

