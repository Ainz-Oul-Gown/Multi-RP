// 1. Вспомогательные функции анализа
function evaluateQuality(narrative, otherPlayerName) {
  const words = (narrative || '').trim().split(/\s+/).filter(Boolean);
  const wordCount = words.length;

  const hasTechTags = /\[(?:Навык|Успех|Провал|Урон|DC|Выживание|Атака|Получен предмет|Выброшен предмет):?[^\]]*\]/i.test(narrative);
  // Расширенный словарь чувственных маркеров с учётом русской морфологии
  const sensoryKeywords = /(?:слыш|звук|ветер|запах|аромат|холод|мороз|тепл|свет|тен[ьи]|мерца|скрип|кап[ле]|треск|пар[а-я]*|гул|тин[аеы]|туман|лед|льдин|плам[яе]|плеск|эхо|сырост|хруст|звон|блеск)/i;
  const hasSensory = sensoryKeywords.test(narrative);

  const forcedSpeechPattern = new RegExp(`${otherPlayerName}\\s+(?:ответил[а-я]*|сказал[а-я]*|возразил[а-я]*|согласил[а-я]*|крикнул[а-я]*|прошептал[а-я]*)\\s*[:«"']`, 'i');
  const forcedAgreementPattern = new RegExp(`${otherPlayerName}\\s+(?:кивнул[а-я]*\\s+и\\s+согласил[а-я]*|с\\s+радостью\\s+согласил[а-я]*|отказал[а-я]*сь)`, 'i');
  const forcedActionPattern = new RegExp(`${otherPlayerName}\\s+(?:выхватил[а-я]*|напал[а-я]*|побежал[а-я]*|выпил[а-я]*\\s+залпом)`, 'i');

  const violations = [];
  if (forcedSpeechPattern.test(narrative)) violations.push('Принудительная речь');
  if (forcedAgreementPattern.test(narrative)) violations.push('Принудительное решение/согласие');
  if (forcedActionPattern.test(narrative)) violations.push('Принудительное физическое действие');

  return {
    wordCount,
    isSufficientLength: wordCount >= 50,
    noTechTags: !hasTechTags,
    hasSensory,
    noPuppeteering: violations.length === 0,
    violations,
  };
}

